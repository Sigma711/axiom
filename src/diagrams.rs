/// 锤子线 / 上吊线 - 重要 K 线形态
/// 锤子线: 出现在下跌趋势底部, 下影线长, 是反转看涨信号
/// 上吊线: 出现在上涨趋势顶部, 下影线长但位置不同, 是反转看跌信号
pub fn hammer_diagram() -> String {
    r#"锤子线 / 上吊线 (Hammer / Hanging Man):
   特征: 小实体 + 长下影线 (≥ 实体 2 倍) + 短上影线
   锤子线 (底部反转):     上吊线 (顶部反转):
     │                       │
     █ (上影短)              █ (上影短)
     █ ─┐                    █ ─┐
       │                      │
       │ ╲                    │ ╲
       │  ╲                   │  ╲
       │   ▓▓▓▓               │   ▓▓▓▓ (实体)
       │      ╲               │      ╲
       │       ╲              │       ╲
       │        ▓▓▓▓▓▓▓▓▓▓    │        ▓▓▓▓▓▓▓▓▓▓ (下影线)
   ════╪═════════════════════╪═══════════════════
       │                      │
   趋势底部               趋势顶部
   ↓ 跌 → 涨 ↑             ↑ 涨 → 跌 ↓
   确认: 次日阳线收盘价 > 锤子线实体的 50%
"#.to_string()
}

